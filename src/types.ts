export type Vec3 = [number, number, number];

export type CameraMode = "orbit" | "god" | "top" | "isometric";
export type ToolMode = "inspect" | "annotate" | "connect" | "measure";
export type AnnotationShape = "point" | "box";
export type CoordinateSpace = "model-local";

export type AnnotationType =
  | "building"
  | "floor"
  | "classroom"
  | "door"
  | "stair"
  | "exit"
  | "hallway"
  | "navigation-node"
  | "assembly-area"
  | "football-field"
  | "restricted-area"
  | "fire-source"
  | "custom";

export type ConnectionType =
  | "walkway"
  | "doorway"
  | "stair"
  | "outdoor-path"
  | "custom";

export interface ProjectInfo {
  name: string;
  schoolName: string;
  description: string;
  createdAt: string;
  updatedAt: string;
}

export interface Calibration {
  position: Vec3;
  rotation: Vec3;
  scale: number;
}

export interface SurfaceHit {
  /** Position in model-local coordinates. */
  position: Vec3;
  /** Position after Calibration in scene/world coordinates. */
  worldPosition: Vec3;
  normal: Vec3;
  objectName: string;
  objectPath: string;
  materialName: string;
  triangleCount: number;
}

export interface SemanticAnnotation {
  id: string;
  type: AnnotationType;
  shape: AnnotationShape;
  name: string;
  position: Vec3;
  rotation: Vec3;
  size: Vec3;
  buildingId: string;
  floor: number | null;
  peopleCount: number;
  capacity: number;
  notes: string;
  tags: string[];
  visible: boolean;
  locked: boolean;
  sourceObjectName: string;
  sourceObjectPath: string;
  createdAt: string;
  updatedAt: string;
}

export interface SemanticConnection {
  id: string;
  fromId: string;
  toId: string;
  type: ConnectionType;
  width: number;
  capacityPerSecond: number;
  bidirectional: boolean;
  enabled: boolean;
  notes: string;
}

export interface ModelReportItem {
  path: string;
  name: string;
  kind: "mesh" | "group" | "object";
  position: Vec3;
  size: Vec3;
  triangleCount: number;
  materialNames: string[];
}

export interface ModelReport {
  modelName: string;
  fileSize: number;
  sha256: string;
  objectCount: number;
  meshCount: number;
  materialCount: number;
  triangleCount: number;
  boundsMin: Vec3;
  boundsMax: Vec3;
  boundsSize: Vec3;
  boundsCenter: Vec3;
  items: ModelReportItem[];
}

export interface ModelSourceInfo {
  name: string;
  size: number;
  sha256: string;
  source: "demo" | "public" | "uploaded" | "generated";
}

export interface SemanticMapFileV2 {
  schema: "skr-semantic-map";
  version: 2;
  exportedAt: string;
  coordinateSpace: CoordinateSpace;
  project: ProjectInfo;
  model: ModelSourceInfo;
  calibration: Calibration;
  modelReport: ModelReport | null;
  annotations: SemanticAnnotation[];
  connections: SemanticConnection[];
}

/** Legacy format generated by Semantic Mapper v1. */
export interface SemanticMapFileV1 {
  schema: "skr-semantic-map";
  version: 1;
  exportedAt: string;
  model: ModelSourceInfo;
  calibration: Calibration;
  modelReport: ModelReport | null;
  annotations: Array<Omit<SemanticAnnotation, "tags" | "visible" | "locked">>;
  connections: Array<Omit<SemanticConnection, "enabled">>;
}

export type SemanticMapFile = SemanticMapFileV2;
export type ImportableSemanticMap = SemanticMapFileV1 | SemanticMapFileV2;

export interface AnnotationDraft {
  hit: SurfaceHit;
  type: AnnotationType;
  shape: AnnotationShape;
  name: string;
  buildingId: string;
  floor: number | null;
  peopleCount: number;
  capacity: number;
  size: Vec3;
  notes: string;
  tagsText: string;
}

export interface MeasurementState {
  start: Vec3 | null;
  end: Vec3 | null;
}

export type ValidationSeverity = "error" | "warning" | "info" | "success";

export interface ValidationIssue {
  id: string;
  severity: ValidationSeverity;
  title: string;
  detail: string;
  annotationId?: string;
}

export interface MapValidationResult {
  score: number;
  issues: ValidationIssue[];
  reachableClassrooms: number;
  totalClassrooms: number;
  totalPeople: number;
}
