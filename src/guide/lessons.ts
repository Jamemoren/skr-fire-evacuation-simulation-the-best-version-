export const LEVELS: LessonLevel[] = ["พื้นฐาน", "กลาง", "ขั้นสูง"];
export const totalMinutes = () => LESSONS.reduce((sum, lesson) => sum + lesson.minutes, 0);

export function searchLessons(query: string): Lesson[] {
  const words = query.trim().toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return LESSONS;
  return LESSONS.filter((lesson) => {
    const text = [lesson.label, lesson.title, lesson.purpose, lesson.see, lesson.keywords ?? "", ...lesson.where, ...lesson.check].join(" ").toLowerCase();
    return words.every((word) => text.includes(word));
  });
}

// ---------------------------------------------------------------- progress (remembered)
const PROGRESS_KEY = "skr-guide-progress";
export interface GuideProgress { last: string; done: string[] }
export function loadProgress(): GuideProgress {
  try {
    const data = JSON.parse(window.localStorage.getItem(PROGRESS_KEY) ?? "null") as Partial<GuideProgress> | null;
    const ids = new Set(LESSONS.map((lesson) => lesson.id));
    return { last: data?.last && ids.has(data.last) ? data.last : LESSONS[0].id, done: Array.isArray(data?.done) ? data.done.filter((id) => ids.has(id)) : [] };
  } catch { return { last: LESSONS[0].id, done: [] }; }
}
export function saveProgress(progress: GuideProgress) {
  try { window.localStorage.setItem(PROGRESS_KEY, JSON.stringify(progress)); } catch { /* private mode */ }
}
